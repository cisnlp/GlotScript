"""
Regenerate GlotScript/ranges.py (SCRIPT_RANGES) from the Unicode Character Database.

    python -m GlotScript.update                    # the Unicode version in ranges.py
    python -m GlotScript.update --version 18.0.0   # another version ("latest" for the newest)
    python -m GlotScript.update --check            # only report whether ranges.py matches the data

Script names in Scripts.txt are mapped to their ISO 15924 codes with PropertyValueAliases.txt (property "sc"), and
consecutive ranges are merged. GlotScript then applies its own changes (ADJUSTMENTS below). Downloads are kept in
~/.cache/glotscript/<version>.
"""
import argparse
import datetime
import os
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

UCD_URL = "https://www.unicode.org/Public/{version}/ucd/{name}"
LATEST_URL = "https://www.unicode.org/Public/UCD/latest/ucd/{name}"
RANGES_FILE = Path(__file__).with_name("ranges.py")

# GlotScript's changes to the Unicode data: (first code point, last code point, script it is moved to, why).
ADJUSTMENTS = [
    (0x064B, 0x0655, "Arab", "Arabic harakat (fathatan .. hamza below) are Inherited in Unicode but used in Arabic script text"),
    (0x0670, 0x0670, "Arab", "ARABIC LETTER SUPERSCRIPT ALEF, Inherited in Unicode"),
    (0xFFFD, 0xFFFD, "Zzzz", "REPLACEMENT CHARACTER stands for a character of unknown script (Common in Unicode)"),
]


def fetch(version, name, cache):
    """Path of a UCD file for a version, downloaded into the cache directory if needed."""
    path = cache / name
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        url = LATEST_URL.format(name=name) if version == "latest" else UCD_URL.format(version=version, name=name)
        print("downloading", url, file=sys.stderr)
        urllib.request.urlretrieve(url, path)
    return path


def script_codes(aliases_path):
    """Unicode script long names -> ISO 15924 codes, from PropertyValueAliases.txt."""
    codes = {}
    for line in open(aliases_path, encoding="utf-8"):
        parts = [p.strip() for p in line.split("#")[0].split(";")]
        if len(parts) >= 3 and parts[0] == "sc":
            codes[parts[2]] = parts[1]
    return codes


def build(scripts_path, aliases_path):
    """SCRIPT_RANGES from the two UCD files with ADJUSTMENTS applied: script -> sorted merged (start, end) ranges."""
    codes = script_codes(aliases_path)
    owner = {}
    for line in open(scripts_path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cps, name = [x.strip() for x in line.split(";")]
        if name not in codes:
            raise ValueError("script %r of Scripts.txt has no ISO 15924 code in PropertyValueAliases.txt" % name)
        a, b = (cps.split("..") + [cps])[:2]
        for o in range(int(a, 16), int(b, 16) + 1):
            owner[o] = codes[name]
    for a, b, script, _ in ADJUSTMENTS:
        for o in range(a, b + 1):
            owner[o] = script
    ranges = defaultdict(list)
    for o in sorted(owner):
        r = ranges[owner[o]]
        if r and r[-1][1] == o - 1:
            r[-1] = (r[-1][0], o)
        else:
            r.append((o, o))
    return {script: ranges[script] for script in sorted(ranges)}


def render(ranges, version, scripts_path):
    header = next((l.strip("# \n") for l in open(scripts_path, encoding="utf-8") if l.startswith("# Date:")), "")
    lines = ['"""',
             "Code point ranges of each script (ISO 15924), generated by `python -m GlotScript.update` from Unicode %s" % version,
             "(Scripts.txt, %s; PropertyValueAliases.txt) with GlotScript's adjustments:" % header,
             ""]
    lines += ["- U+%04X..U+%04X -> %s: %s" % (a, b, s, why) for a, b, s, why in ADJUSTMENTS]
    lines += ["", "Do not edit by hand: change GlotScript/update.py and run it again.", '"""', "",
              "UNICODE_VERSION = %r" % version, "", "SCRIPT_RANGES = {"]
    lines += ["    %r: %s," % (script, ranges[script]) for script in ranges]
    lines += ["}", ""]
    return "\n".join(lines)


def current_version():
    try:
        sys.path.insert(0, str(RANGES_FILE.parent))
        import ranges as current  # noqa: E402
        return current.UNICODE_VERSION, current.SCRIPT_RANGES
    except ImportError:
        return None, None
    finally:
        sys.path.pop(0)


def main():
    ap = argparse.ArgumentParser(description="Regenerate GlotScript/ranges.py from the Unicode Character Database.")
    ap.add_argument("--version", help="Unicode version, e.g. 18.0.0, or latest (default: the version in ranges.py)")
    ap.add_argument("--check", action="store_true", help="only report whether ranges.py matches the data")
    ap.add_argument("--cache", default=os.path.join(os.path.expanduser("~"), ".cache", "glotscript"))
    a = ap.parse_args()
    cur_version, cur_ranges = current_version()
    version = a.version or cur_version or "latest"
    cache = Path(a.cache) / version
    scripts_path = fetch(version, "Scripts.txt", cache)
    aliases_path = fetch(version, "PropertyValueAliases.txt", cache)
    ranges = build(scripts_path, aliases_path)
    if a.check:
        same = cur_ranges == ranges and list(cur_ranges or {}) == list(ranges)
        print("ranges.py matches Unicode %s" % version if same else "ranges.py differs from Unicode %s" % version)
        sys.exit(0 if same else 1)
    RANGES_FILE.write_text(render(ranges, version, scripts_path), encoding="utf-8")
    print("wrote %s: %d scripts, Unicode %s" % (RANGES_FILE, len(ranges), version))


if __name__ == "__main__":
    main()
